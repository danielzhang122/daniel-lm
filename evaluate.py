"""Save fixed-prompt CPU samples; optionally watch for new checkpoints."""
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import time
from sample_store import save

ROOT=Path(__file__).parent
PROMPTS=['The Solar System consists of','Electricity is generated by','The history of computing began with']


def evaluate(run):
    folder=ROOT/'runs'/run
    config=json.loads((folder/'run.json').read_text())
    for prompt in PROMPTS:
        result=subprocess.run([sys.executable,str(ROOT/'generate.py'),'--checkpoint',str(folder/'latest.pt'),
            '--tokenizer',str(Path(config['data'])/'tokenizer.json'),'--prompt',prompt,'--tokens','60','--device','cpu','--json'],
            capture_output=True,text=True,encoding='utf-8',env={**os.environ,'PYTHONIOENCODING':'utf-8'},timeout=120,check=True)
        sample=json.loads(result.stdout)
        save(run,prompt,sample,requested_tokens=60)
        print(f"Saved {run} step {sample['step']}: {prompt}",flush=True)


if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--run',default='full')
    p.add_argument('--watch',action='store_true')
    p.add_argument('--interval',type=int,default=900)
    args=p.parse_args()
    import re
    if not re.fullmatch(r'[A-Za-z0-9_-]+',args.run) or args.interval<60: p.error('Invalid run or interval (minimum 60s)')
    last=None
    while True:
        checkpoint=ROOT/'runs'/args.run/'latest.pt'
        stamp=checkpoint.stat().st_mtime_ns if checkpoint.exists() else None
        if stamp and stamp!=last:
            try:
                evaluate(args.run)
                last=stamp
            except (subprocess.SubprocessError,ValueError,OSError) as exc:
                print(f'Evaluation failed: {exc}',flush=True)
                if not args.watch: raise
        if not args.watch: break
        time.sleep(args.interval)
